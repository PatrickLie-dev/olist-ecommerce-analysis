-- ----------------------------------------------------------
-- Q1. How many orders does Olist have in total?
-- Business use: Baseline KPI for business size overview
-- ----------------------------------------------------------
SELECT COUNT(order_id) AS total_orders
FROM olist_orders_dataset;


-- ----------------------------------------------------------
-- Q2. What are the possible order statuses and how many per status?
-- Business use: Order fulfillment health check
-- ----------------------------------------------------------
SELECT
    order_status,
    COUNT(order_id) AS total_orders
FROM olist_orders_dataset
GROUP BY order_status
ORDER BY total_orders DESC;


-- ----------------------------------------------------------
-- Q3. Which are the top 10 product categories by number of items sold?
-- Business use: Identify bestselling categories for inventory planning
-- ----------------------------------------------------------
SELECT
    cat.product_category_name_english AS category,
    COUNT(oi.order_item_id)           AS items_sold
FROM olist_order_items_dataset oi
JOIN olist_products_dataset pr
    ON oi.product_id = pr.product_id
JOIN olist_product_category_name_translation cat
    ON pr.product_category_name = cat.product_category_name
GROUP BY cat.product_category_name_english
ORDER BY items_sold DESC
LIMIT 10;


-- ----------------------------------------------------------
-- Q4. What is the total revenue generated by Olist?
-- Business use: Top-line revenue reporting
-- ----------------------------------------------------------
SELECT
    ROUND(SUM(payment_value), 2) AS total_revenue_brl
FROM olist_order_payments_dataset;


-- ----------------------------------------------------------
-- Q5. What is the average order review score?
-- Business use: Customer satisfaction benchmark
-- ----------------------------------------------------------
SELECT
    ROUND(AVG(review_score), 2) AS avg_review_score
FROM olist_order_reviews_dataset;


-- ----------------------------------------------------------
-- Q6. Which states have the most customers?
-- Business use: Geographic market concentration analysis
-- ----------------------------------------------------------
SELECT
    customer_state,
    COUNT(customer_id) AS total_customers
FROM olist_customers_dataset
GROUP BY customer_state
ORDER BY total_customers DESC
LIMIT 10;


-- ----------------------------------------------------------
-- Q7. How many orders were placed each year?
-- Business use: Year-over-year growth tracking
-- ----------------------------------------------------------
SELECT
    YEAR(order_purchase_timestamp)  AS year,
    COUNT(order_id)                 AS total_orders
FROM olist_orders_dataset
GROUP BY YEAR(order_purchase_timestamp)
ORDER BY year;


-- ----------------------------------------------------------
-- Q8. What payment types do customers prefer?
-- Business use: Payment channel optimization
-- ----------------------------------------------------------
SELECT
    payment_type,
    COUNT(order_id)                                         AS usage_count,
    ROUND(SUM(payment_value), 2)                            AS total_value_brl,
    ROUND(AVG(payment_value), 2)                            AS avg_value_brl
FROM olist_order_payments_dataset
GROUP BY payment_type
ORDER BY usage_count DESC;


-- ============================================================
-- LEVEL 2: INTERMEDIATE
-- Core: JOINs, Subqueries, CASE WHEN, date functions, HAVING
-- ============================================================

-- ----------------------------------------------------------
-- Q9. What is the monthly revenue trend? (2017–2018)
-- Business use: Seasonality and growth trend analysis
-- ----------------------------------------------------------
SELECT
    DATE_FORMAT(o.order_purchase_timestamp, '%Y-%m') AS month,
    ROUND(SUM(p.payment_value), 2)                    AS monthly_revenue_brl,
    COUNT(DISTINCT o.order_id)                        AS total_orders
FROM olist_orders_dataset o
JOIN olist_order_payments_dataset p
    ON o.order_id = p.order_id
WHERE o.order_status = 'delivered'
GROUP BY DATE_FORMAT(o.order_purchase_timestamp, '%Y-%m')
ORDER BY month;


-- ----------------------------------------------------------
-- Q10. What is the average delivery time per state?
-- Business use: Logistics performance benchmarking by region
-- ----------------------------------------------------------
SELECT
    c.customer_state,
    COUNT(o.order_id)                                              AS delivered_orders,
    ROUND(AVG(DATEDIFF(
        o.order_delivered_customer_date,
        o.order_purchase_timestamp
    )), 1)                                                         AS avg_delivery_days
FROM olist_orders_dataset o
JOIN olist_customers_dataset c
    ON o.customer_id = c.customer_id
WHERE o.order_status = 'delivered'
  AND o.order_delivered_customer_date IS NOT NULL
GROUP BY c.customer_state
ORDER BY avg_delivery_days ASC;


-- ----------------------------------------------------------
-- Q11. Which sellers generate the most revenue?
-- Business use: Top seller identification for partnership programs
-- ----------------------------------------------------------
SELECT
    oi.seller_id,
    s.seller_city,
    s.seller_state,
    COUNT(DISTINCT oi.order_id)         AS total_orders,
    ROUND(SUM(oi.price), 2)             AS total_revenue_brl,
    ROUND(AVG(oi.price), 2)             AS avg_order_value_brl
FROM olist_order_items_dataset oi
JOIN olist_sellers_dataset s
    ON oi.seller_id = s.seller_id
GROUP BY oi.seller_id, s.seller_city, s.seller_state
ORDER BY total_revenue_brl DESC
LIMIT 20;


-- ----------------------------------------------------------
-- Q12. What is the relationship between delivery time and review score?
-- Business use: Prove fast delivery = better reviews (SLA justification)
-- ----------------------------------------------------------
SELECT
    CASE
        WHEN DATEDIFF(o.order_delivered_customer_date, o.order_purchase_timestamp) <= 7  THEN '0–7 days'
        WHEN DATEDIFF(o.order_delivered_customer_date, o.order_purchase_timestamp) <= 14 THEN '8–14 days'
        WHEN DATEDIFF(o.order_delivered_customer_date, o.order_purchase_timestamp) <= 21 THEN '15–21 days'
        WHEN DATEDIFF(o.order_delivered_customer_date, o.order_purchase_timestamp) <= 30 THEN '22–30 days'
        ELSE '30+ days'
    END                             AS delivery_bucket,
    COUNT(o.order_id)               AS total_orders,
    ROUND(AVG(r.review_score), 2)   AS avg_review_score
FROM olist_orders_dataset o
JOIN olist_order_reviews_dataset r
    ON o.order_id = r.order_id
WHERE o.order_status = 'delivered'
  AND o.order_delivered_customer_date IS NOT NULL
GROUP BY delivery_bucket
ORDER BY avg_review_score DESC;


-- ----------------------------------------------------------
-- Q13. Which product categories have the highest average review score?
-- (minimum 100 reviews for statistical significance)
-- Business use: Quality benchmarking by category
-- ----------------------------------------------------------
SELECT
    cat.product_category_name_english   AS category,
    COUNT(r.review_id)                  AS total_reviews,
    ROUND(AVG(r.review_score), 2)       AS avg_review_score
FROM olist_order_reviews_dataset r
JOIN olist_orders_dataset o
    ON r.order_id = o.order_id
JOIN olist_order_items_dataset oi
    ON o.order_id = oi.order_id
JOIN olist_products_dataset pr
    ON oi.product_id = pr.product_id
JOIN olist_product_category_name_translation cat
    ON pr.product_category_name = cat.product_category_name
GROUP BY cat.product_category_name_english
HAVING COUNT(r.review_id) >= 100
ORDER BY avg_review_score DESC
LIMIT 15;


-- ----------------------------------------------------------
-- Q14. What percentage of orders were delivered late?
-- Business use: SLA breach rate — operational KPI
-- ----------------------------------------------------------
SELECT
    COUNT(order_id)                                                     AS total_delivered,
    SUM(CASE
        WHEN order_delivered_customer_date > order_estimated_delivery_date
        THEN 1 ELSE 0
    END)                                                                AS late_orders,
    ROUND(
        100.0 * SUM(CASE
            WHEN order_delivered_customer_date > order_estimated_delivery_date
            THEN 1 ELSE 0
        END) / COUNT(order_id), 2
    )                                                                   AS late_rate_pct
FROM olist_orders_dataset
WHERE order_status = 'delivered'
  AND order_delivered_customer_date IS NOT NULL;


-- ----------------------------------------------------------
-- Q15. Repeat vs. one-time customers — what is the split?
-- Business use: Customer loyalty and retention baseline
-- ----------------------------------------------------------
SELECT
    purchase_frequency,
    COUNT(customer_unique_id)   AS customer_count,
    ROUND(
        100.0 * COUNT(customer_unique_id) / SUM(COUNT(customer_unique_id)) OVER(),
        2
    )                           AS pct_of_total
FROM (
    SELECT
        c.customer_unique_id,
        CASE
            WHEN COUNT(DISTINCT o.order_id) = 1 THEN 'One-time'
            ELSE 'Repeat'
        END AS purchase_frequency
    FROM olist_customers_dataset c
    JOIN olist_orders_dataset o
        ON c.customer_id = o.customer_id
    GROUP BY c.customer_unique_id
) AS customer_segments
GROUP BY purchase_frequency;


