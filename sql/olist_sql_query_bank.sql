-- ----------------------------------------------------------
-- Q16. RFM Customer Segmentation
-- Business use: Marketing segmentation — rank customers by
--               Recency, Frequency, Monetary value
-- ----------------------------------------------------------
WITH rfm_raw AS (
    SELECT
        c.customer_unique_id,
        MAX(o.order_purchase_timestamp)             AS last_purchase_date,
        COUNT(DISTINCT o.order_id)                  AS frequency,
        ROUND(SUM(p.payment_value), 2)              AS monetary
    FROM olist_customers_dataset c
    JOIN olist_orders_dataset o
        ON c.customer_id = o.customer_id
    JOIN olist_order_payments_dataset p
        ON o.order_id = p.order_id
    WHERE o.order_status = 'delivered'
    GROUP BY c.customer_unique_id
),
rfm_scored AS (
    SELECT
        customer_unique_id,
        DATEDIFF('2018-10-17', last_purchase_date)  AS recency_days,
        frequency,
        monetary,
        NTILE(5) OVER (ORDER BY DATEDIFF('2018-10-17', last_purchase_date) ASC)  AS r_score,
        NTILE(5) OVER (ORDER BY frequency DESC)                                  AS f_score,
        NTILE(5) OVER (ORDER BY monetary DESC)                                   AS m_score
    FROM rfm_raw
)
SELECT
    customer_unique_id,
    recency_days,
    frequency,
    monetary,
    r_score,
    f_score,
    m_score,
    (r_score + f_score + m_score)   AS rfm_total_score,
    CASE
        WHEN (r_score + f_score + m_score) >= 13 THEN 'Champions'
        WHEN (r_score + f_score + m_score) >= 10 THEN 'Loyal Customers'
        WHEN (r_score + f_score + m_score) >= 7  THEN 'Potential Loyalists'
        WHEN (r_score + f_score + m_score) >= 5  THEN 'At Risk'
        ELSE 'Lost'
    END                             AS rfm_segment
FROM rfm_scored
ORDER BY rfm_total_score DESC;


-- ----------------------------------------------------------
-- Q17. Month-over-Month (MoM) revenue growth rate
-- Business use: Executive dashboard — growth velocity tracking
-- ----------------------------------------------------------
WITH monthly_revenue AS (
    SELECT
        DATE_FORMAT(o.order_purchase_timestamp, '%Y-%m')    AS month,
        ROUND(SUM(p.payment_value), 2)                      AS revenue
    FROM olist_orders_dataset o
    JOIN olist_order_payments_dataset p
        ON o.order_id = p.order_id
    WHERE o.order_status = 'delivered'
    GROUP BY DATE_FORMAT(o.order_purchase_timestamp, '%Y-%m')
)
SELECT
    month,
    revenue,
    LAG(revenue) OVER (ORDER BY month)                          AS prev_month_revenue,
    ROUND(
        100.0 * (revenue - LAG(revenue) OVER (ORDER BY month))
              / NULLIF(LAG(revenue) OVER (ORDER BY month), 0),
        2
    )                                                           AS mom_growth_pct
FROM monthly_revenue
ORDER BY month;


-- ----------------------------------------------------------
-- Q18. Running cumulative revenue by month
-- Business use: Progress-to-target tracking on dashboards
-- ----------------------------------------------------------
WITH monthly AS (
    SELECT
        DATE_FORMAT(o.order_purchase_timestamp, '%Y-%m')    AS month,
        ROUND(SUM(p.payment_value), 2)                      AS monthly_revenue
    FROM olist_orders_dataset o
    JOIN olist_order_payments_dataset p ON o.order_id = p.order_id
    WHERE o.order_status = 'delivered'
    GROUP BY DATE_FORMAT(o.order_purchase_timestamp, '%Y-%m')
)
SELECT
    month,
    monthly_revenue,
    ROUND(SUM(monthly_revenue) OVER (ORDER BY month ROWS UNBOUNDED PRECEDING), 2) AS cumulative_revenue
FROM monthly
ORDER BY month;


-- ----------------------------------------------------------
-- Q19. Top 3 sellers per state by revenue (ranking within group)
-- Business use: Regional leaderboard — seller performance report
-- ----------------------------------------------------------
WITH seller_revenue AS (
    SELECT
        s.seller_state,
        oi.seller_id,
        ROUND(SUM(oi.price), 2) AS revenue
    FROM olist_order_items_dataset oi
    JOIN olist_sellers_dataset s
        ON oi.seller_id = s.seller_id
    GROUP BY s.seller_state, oi.seller_id
),
ranked AS (
    SELECT
        seller_state,
        seller_id,
        revenue,
        RANK() OVER (PARTITION BY seller_state ORDER BY revenue DESC) AS state_rank
    FROM seller_revenue
)
SELECT *
FROM ranked
WHERE state_rank <= 3
ORDER BY seller_state, state_rank;


-- ----------------------------------------------------------
-- Q20. Cohort Retention Analysis (purchase cohort by month)
-- Business use: Measure how well Olist retains customers month-by-month
-- ----------------------------------------------------------
WITH first_purchase AS (
    SELECT
        c.customer_unique_id,
        MIN(DATE_FORMAT(o.order_purchase_timestamp, '%Y-%m')) AS cohort_month
    FROM olist_customers_dataset c
    JOIN olist_orders_dataset o ON c.customer_id = o.customer_id
    GROUP BY c.customer_unique_id
),
customer_activity AS (
    SELECT
        c.customer_unique_id,
        DATE_FORMAT(o.order_purchase_timestamp, '%Y-%m') AS activity_month
    FROM olist_customers_dataset c
    JOIN olist_orders_dataset o ON c.customer_id = o.customer_id
),
cohort_data AS (
    SELECT
        f.cohort_month,
        a.activity_month,
        COUNT(DISTINCT a.customer_unique_id) AS active_customers
    FROM first_purchase f
    JOIN customer_activity a USING (customer_unique_id)
    GROUP BY f.cohort_month, a.activity_month
)
SELECT
    cohort_month,
    activity_month,
    active_customers,
    FIRST_VALUE(active_customers) OVER (
        PARTITION BY cohort_month ORDER BY activity_month
    )                                               AS cohort_size,
    ROUND(
        100.0 * active_customers /
        FIRST_VALUE(active_customers) OVER (
            PARTITION BY cohort_month ORDER BY activity_month
        ), 2
    )                                               AS retention_rate_pct
FROM cohort_data
ORDER BY cohort_month, activity_month;


