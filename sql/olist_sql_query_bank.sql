-- BONUS: BUSINESS INSIGHT QUERY
-- ----------------------------------------------------------
-- Q21. Full order summary — one query to rule them all
-- Business use: Master fact table for dashboard data source
-- ============================================================
SELECT
    o.order_id,
    o.order_status,
    o.order_purchase_timestamp,
    o.order_delivered_customer_date,
    o.order_estimated_delivery_date,
    DATEDIFF(
        o.order_delivered_customer_date,
        o.order_purchase_timestamp
    )                                                           AS actual_delivery_days,
    DATEDIFF(
        o.order_estimated_delivery_date,
        o.order_purchase_timestamp
    )                                                           AS estimated_delivery_days,
    CASE
        WHEN o.order_delivered_customer_date > o.order_estimated_delivery_date THEN 'Late'
        WHEN o.order_delivered_customer_date IS NULL THEN 'Not Delivered'
        ELSE 'On Time'
    END                                                         AS delivery_status,
    c.customer_state,
    c.customer_city,
    p.payment_type,
    p.payment_installments,
    ROUND(p.payment_value, 2)                                   AS payment_value_brl,
    r.review_score,
    cat.product_category_name_english                           AS product_category
FROM olist_orders_dataset o
LEFT JOIN olist_customers_dataset c
    ON o.customer_id = c.customer_id
LEFT JOIN olist_order_payments_dataset p
    ON o.order_id = p.order_id
LEFT JOIN olist_order_reviews_dataset r
    ON o.order_id = r.order_id
LEFT JOIN olist_order_items_dataset oi
    ON o.order_id = oi.order_id
LEFT JOIN olist_products_dataset pr
    ON oi.product_id = pr.product_id
LEFT JOIN olist_product_category_name_translation cat
    ON pr.product_category_name = cat.product_category_name
ORDER BY o.order_purchase_timestamp DESC;

